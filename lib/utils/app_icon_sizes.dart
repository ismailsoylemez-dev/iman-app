/// Uygulama genelinde kullanılan merkezi ikon boyutu sabitleri.
class AppIconSizes {
  AppIconSizes._();

  // Standard sizes
  static const double small = 16; // Caption, small info
  static const double regular = 18; // Standard leading icon
  static const double medium = 20; // Default icon size
  static const double large = 24; // Prominent button icon
  static const double xlarge = 28; // Large prominent
  static const double xxlarge = 56; // Hero/splash screen

  // Named sizes
  static const double navIcon = 24; // Bottom nav icon
  static const double listLeading = 20; // ListTile leading
  static const double appBarAction = 24; // AppBar action
  static const double floatingButton = 28; // FAB icon
  static const double heroImage = 56; // Large display
}
